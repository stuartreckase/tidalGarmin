#!/usr/bin/env python3
"""Regenerate device support from the installed Connect IQ SDK.

Reads <SDK>/doc/docs/Device_Reference/*.html and keeps every device whose
App Types include "Audio Content Provider". Rewrites:
  watchapp/manifest.xml   <iq:products> list
  watchapp/monkey.jungle  per-device launcher icon (icons/<size>)
  README.md               block between <!-- devices:start/end -->

Usage: tools/gen_devices.py [SDK_DIR]   (default: current-sdk.cfg)
"""
import html
import re
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CIQ = Path.home() / "Library/Application Support/Garmin/ConnectIQ"
DEFAULT_ICON = 40


def text(path):
    t = path.read_text(errors="ignore")
    t = re.sub(r"<script.*?</script>|<style.*?</style>", " ", t, flags=re.S)
    t = re.sub(r"<[^>]+>", " ", t)
    return re.sub(r"\s+", " ", html.unescape(t))


def devices(sdk):
    out = []
    for page in sorted((sdk / "doc/docs/Device_Reference").glob("*.html")):
        t = text(page)
        m = re.search(r"Attribute Value Id (\S+) Screen Shape (\S+) Screen Size (\d+) x (\d+)", t)
        if not m or not re.search(r"App Types .{0,80}Audio Content Provider \d+", t[m.end():m.end() + 1200]):
            continue
        icon = re.search(r"Launcher Icon Size (\d+) x \d+", t)
        title = re.search(r"<title>(.*?)</title>", page.read_text(errors="ignore"), flags=re.S)
        out.append({
            "id": m.group(1), "shape": m.group(2), "w": int(m.group(3)), "h": int(m.group(4)),
            "icon": int(icon.group(1)) if icon else DEFAULT_ICON,
            "name": re.sub(r"\s+", " ", html.unescape(title.group(1))).strip() if title else m.group(1),
        })
    return out


def write_manifest(devs):
    p = REPO / "watchapp/manifest.xml"
    s = p.read_text()
    products = "\n".join(f'            <iq:product id="{d["id"]}"/>' for d in devs)
    s = re.sub(r"<iq:products>.*?</iq:products>",
               f"<iq:products>\n{products}\n        </iq:products>", s, flags=re.S)
    p.write_text(s)


def installed(dev_id):
    # informational: build.sh filters jungle lines for missing packs itself
    return (CIQ / "Devices" / dev_id / "compiler.json").exists()


def write_jungle(devs):
    lines = [
        "# generated by tools/gen_devices.py — edit that, not this",
        "project.manifest = manifest.xml",
        "base.sourcePath = source",
        f"base.resourcePath = resources;icons/{DEFAULT_ICON}",
        "",
        "# launcher icon per device (Device_Reference 'Launcher Icon Size')",
    ]
    lines += [f"{d['id']}.resourcePath = resources;icons/{d['icon']}"
              for d in devs if d["icon"] != DEFAULT_ICON]
    (REPO / "watchapp/monkey.jungle").write_text("\n".join(lines) + "\n")


def family(name):
    for f in ("Approach", "D2", "Descent", "Enduro", "epix", "fēnix", "Forerunner",
              "Legacy", "MARQ", "Venu", "vívoactive", "Bounce"):
        if name.lower().startswith(f.lower()):
            return f
    return "Other"


def write_readme(devs):
    groups = defaultdict(list)
    for d in devs:
        groups[family(d["name"])].append(d)
    rows = ["| Family | Models (`device id`) |", "|---|---|"]
    for f in sorted(groups, key=str.lower):
        cells = "<br>".join(f"{d['name']} (`{d['id']}`)" for d in sorted(groups[f], key=lambda d: d["name"]))
        rows.append(f"| {f} | {cells} |")
    block = (
        "<!-- devices:start (generated by tools/gen_devices.py) -->\n"
        f"{len(devs)} models: every Connect IQ device whose SDK reference lists the Audio\n"
        "Content Provider app type (Wi-Fi music watches), Connect IQ 3.1+.\n\n"
        "- **Tested on hardware:** fēnix 8 Solar 47mm.\n"
        "- **Prebuilt in releases:** a few common models (see the release notes).\n"
        "- **Everything else:** untested; build your own with `./build.sh <device id>`\n"
        "  after downloading the device pack in SDK Manager.\n\n"
        + "\n".join(rows) + "\n<!-- devices:end -->")
    p = REPO / "README.md"
    s = p.read_text()
    if "<!-- devices:start" in s:
        s = re.sub(r"<!-- devices:start.*?<!-- devices:end -->", lambda _: block, s, flags=re.S)
    else:
        s = s.replace("## Requirements", "## Supported watches\n\n" + block + "\n\n## Requirements", 1)
    p.write_text(s)


def main():
    sdk = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(
        (CIQ / "current-sdk.cfg").read_text().strip().splitlines()[0].rstrip("/"))
    devs = devices(sdk)
    write_manifest(devs)
    write_jungle(devs)
    write_readme(devs)
    sizes = sorted({d["icon"] for d in devs})
    missing = [d["id"] for d in devs if not installed(d["id"])]
    print(f"{len(devs)} devices; icon sizes {sizes}")
    if missing:
        print(f"{len(missing)} device packs not downloaded (SDK Manager > Devices); "
              "build.sh skips their jungle lines until they are")


if __name__ == "__main__":
    sys.exit(main())
