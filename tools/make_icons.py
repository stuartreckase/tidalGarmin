#!/usr/bin/env python3
"""Render the launcher icon at every size Connect IQ devices use.

Writes watchapp/icons/<size>/launcher.png + drawables.xml. Each device is
pointed at its size in watchapp/monkey.jungle (generated by gen_devices.py).
Requires Pillow.
"""
import math
import sys
from pathlib import Path

from PIL import Image, ImageDraw

SIZES = [30, 35, 36, 40, 54, 56, 60, 61, 65, 70]
ROOT = Path(__file__).resolve().parent.parent / "watchapp" / "icons"


def master(s=560):
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    k = s / 320
    d.ellipse((4 * k, 4 * k, s - 4 * k, s - 4 * k), fill=(0, 34, 68, 255))

    def wave(y0, amp, width, color):
        r = width * k / 2
        for i in range(901):
            t = i / 900
            x = (40 + t * 240) * k
            y = (y0 + amp * math.sin(2 * math.pi * 1.5 * t)) * k
            d.ellipse((x - r, y - r, x + r, y + r), fill=color)

    wave(118, 22, 30, (0, 255, 255, 255))
    wave(178, 22, 30, (0, 170, 255, 255))
    wave(238, 16, 22, (0, 85, 170, 255))
    return img


def main():
    m = master()
    for n in SIZES:
        out = ROOT / str(n)
        out.mkdir(parents=True, exist_ok=True)
        m.resize((n, n), Image.LANCZOS).save(out / "launcher.png")
        (out / "drawables.xml").write_text(
            '<resources>\n    <drawables>\n'
            '        <bitmap id="LauncherIcon" filename="launcher.png"/>\n'
            '    </drawables>\n</resources>\n')
    print("icons:", ", ".join(map(str, SIZES)), "->", ROOT)


if __name__ == "__main__":
    sys.exit(main())
